// Counts how many of the 1,000,000 numbers earn each achievement and writes
// counts.js. Run after adding or changing achievements: npm run counts
import { writeFileSync } from "node:fs";
import { ACHIEVEMENTS, earnedIds } from "../achievements.js";
import { MIN, MAX } from "../classify.js";

export function countAll() {
  const counts = Object.fromEntries(ACHIEVEMENTS.map((a) => [a.id, 0]));
  for (let n = MIN; n <= MAX; n++)
    for (const id of earnedIds(n).keys()) if (id in counts) counts[id]++;
  return counts;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const counts = countAll();
  const body = Object.entries(counts).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join("\n");
  writeFileSync(new URL("../counts.js", import.meta.url),
    `// Generated by \`npm run counts\` — how many of the 1,000,000 numbers earn each achievement.\nexport default {\n${body}\n};\n`);
  const zero = Object.entries(counts).filter(([, v]) => !v).map(([k]) => k);
  console.log(`${ACHIEVEMENTS.length} achievements counted.`, zero.length ? `Never earned: ${zero.join(", ")}` : "All earnable.");
}
